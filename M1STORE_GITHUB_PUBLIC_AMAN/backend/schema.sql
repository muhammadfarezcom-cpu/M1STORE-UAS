CREATE DATABASE IF NOT EXISTS m1store CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE m1store;
CREATE TABLE IF NOT EXISTS products (
 id VARCHAR(120) PRIMARY KEY, game VARCHAR(100) NOT NULL, name VARCHAR(255) NOT NULL,
 section VARCHAR(150), price INT NOT NULL, active BOOLEAN NOT NULL DEFAULT FALSE, stock INT NOT NULL DEFAULT 0,
 supplier_sku VARCHAR(150), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id VARCHAR(50) PRIMARY KEY, product_id VARCHAR(120) NOT NULL,
 product_name VARCHAR(255) NOT NULL, game VARCHAR(100) NOT NULL, unit_price INT NOT NULL,
 quantity INT NOT NULL, total INT NOT NULL, account_id VARCHAR(100) NOT NULL,
 zone_id VARCHAR(100), whatsapp VARCHAR(30) NOT NULL,
 payment_status VARCHAR(50) NOT NULL DEFAULT 'pending', stock_reserved BOOLEAN NOT NULL DEFAULT FALSE,
 fulfillment_status VARCHAR(50) NOT NULL DEFAULT 'not_started',
 snap_token TEXT, snap_redirect_url TEXT, payment_type VARCHAR(100),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payment_events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, order_id VARCHAR(50),
 status VARCHAR(50) NOT NULL, transaction_id VARCHAR(150), payload JSON NOT NULL,
 received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fulfillment_jobs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, order_id VARCHAR(50) NOT NULL UNIQUE,
 supplier VARCHAR(100) NOT NULL DEFAULT 'unconfigured', supplier_reference VARCHAR(150) UNIQUE,
 status VARCHAR(50) NOT NULL DEFAULT 'awaiting_supplier', attempts INT NOT NULL DEFAULT 0,
 last_error TEXT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS customers (id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL,email VARCHAR(190) NOT NULL UNIQUE,whatsapp VARCHAR(30) NOT NULL,password_salt CHAR(32) NOT NULL,password_hash CHAR(128) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS customer_sessions (id BIGINT AUTO_INCREMENT PRIMARY KEY,customer_id BIGINT NOT NULL,token_hash CHAR(64) NOT NULL UNIQUE,expires_at DATETIME NOT NULL,FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE CASCADE) ENGINE=InnoDB;
